"""Dataset card loader and registry."""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

logger = logging.getLogger(__name__)

_DEFAULT_CARDS_DIR = Path("configs/data/datasets")


@dataclass(frozen=True)
class DatasetCard:
    """A dataset card describing an available dataset."""

    name: str
    description: str
    source_root: str
    #: Keyed by storage backend, e.g. {"nfs": "/path/to.parquet", "s3eoz": "s3://..."}.
    manifest: dict[str, str]
    ingestor: str | None = None
    #: AI Data Catalog ID (compliance; e.g. hyperloop transfers). Mandatory — validated at
    #: card load (see :func:`_parse_card`); every dataset must be AIDC-registered before ingest.
    aidc_id: str = ""
    #: Primary spoken language(s), or None if the dataset has no speech (not in the shard).
    language: str | None = None
    #: Repo-relative path to a runnable download script, when one exists.
    download_script: str | None = None
    #: Shard-derived content summary (num_recordings, total_hours, per-modality format);
    #: generated by an external Lance catalog tool.
    contents: dict[str, Any] = field(default_factory=dict)
    #: Derived/enriched Lance artifacts keyed to this dataset by recording_id/clip_id
    #: (name -> s3eoz uri), e.g. WhisperX ASR segments or a tokenized training view.
    #: Derived versions live here rather than as standalone cards — they are only
    #: meaningful alongside the base dataset they were produced from.
    enrich: dict[str, str] = field(default_factory=dict)
    #: Prose fallback for datasets without a runnable download script.
    download: str | None = None
    preprocessing_notes: str | None = None
    extra: dict[str, Any] = field(default_factory=dict)

    @property
    def manifest_path(self) -> str:
        """Return the first available manifest path (prefer the Lance canonical on s3eoz)."""
        for key in ("s3eoz", "nfs"):
            if key in self.manifest:
                return self.manifest[key]
        if not self.manifest:
            msg = f"Dataset card '{self.name}' has no manifest paths configured"
            raise ValueError(msg)
        return next(iter(self.manifest.values()))


def _parse_card(data: dict[str, Any]) -> DatasetCard:
    """Parse a raw YAML dict into a DatasetCard."""
    known_keys = {
        "name",
        "description",
        "source_root",
        "manifest",
        "ingestor",
        "aidc_id",
        "language",
        "download_script",
        "contents",
        "enrich",
        "download",
        "preprocessing_notes",
    }
    extra = {k: v for k, v in data.items() if k not in known_keys}
    aidc_id = data.get("aidc_id")
    if not aidc_id:
        msg = (
            f"Dataset card '{data.get('name')}' is missing a mandatory 'aidc_id'. Every dataset "
            "must be registered in the AI Data Catalog (compliance / hyperloop transfers) before ingest."
        )
        raise ValueError(msg)
    return DatasetCard(
        name=data["name"],
        description=data.get("description", ""),
        source_root=data["source_root"],
        manifest=data["manifest"],
        ingestor=data.get("ingestor"),
        aidc_id=str(aidc_id),
        language=data.get("language"),
        download_script=data.get("download_script"),
        contents=data.get("contents", {}),
        enrich=data.get("enrich", {}),
        download=data.get("download"),
        preprocessing_notes=data.get("preprocessing_notes"),
        extra=extra,
    )


def load_card(name: str, cards_dir: str | Path | None = None) -> DatasetCard:
    """Load a single dataset card by name.

    Args:
        name: Dataset name (matches the YAML filename without extension).
        cards_dir: Directory containing dataset card YAML files.
            Defaults to configs/data/datasets/ relative to repo root.

    Returns:
        The parsed DatasetCard.

    Raises:
        FileNotFoundError: If the card YAML does not exist.
    """
    if cards_dir is None:
        cards_dir = _find_cards_dir()
    cards_dir = Path(cards_dir)
    card_path = cards_dir / f"{name}.yaml"
    if not card_path.exists():
        card_path = cards_dir / f"{name}.yml"
    if not card_path.exists():
        available = list_cards(cards_dir)
        msg = f"Dataset card '{name}' not found in {cards_dir}. Available: {available}"
        raise FileNotFoundError(msg)
    with card_path.open() as f:
        data = yaml.safe_load(f)
    return _parse_card(data)


def list_cards(cards_dir: str | Path | None = None) -> list[str]:
    """List all available dataset card names.

    Args:
        cards_dir: Directory containing dataset card YAML files.

    Returns:
        Sorted list of dataset names.
    """
    if cards_dir is None:
        cards_dir = _find_cards_dir()
    cards_dir = Path(cards_dir)
    if not cards_dir.exists():
        return []
    return [
        p.stem for p in sorted(cards_dir.iterdir()) if p.suffix in (".yaml", ".yml") and not p.name.startswith(".")
    ]


def load_cards(*names: str, cards_dir: str | Path | None = None) -> list[DatasetCard]:
    """Load multiple dataset cards by name.

    Args:
        *names: Dataset names to load.
        cards_dir: Directory containing dataset card YAML files.

    Returns:
        List of parsed DatasetCards in the order requested.
    """
    return [load_card(name, cards_dir=cards_dir) for name in names]


def resolve_manifest_uri(spec: str, *, cards_dir: str | Path | None = None) -> str:
    """Resolve a loader ``manifests`` entry to a concrete URI, via the dataset card when named.

    Accepts three forms so configs can reference the card (single source of truth) instead of
    pasting URIs:

    * ``"s3://…"`` / ``"/nfs/…"`` / ``"train.parquet"`` — a raw URI or path, returned unchanged.
    * ``"<dataset>"`` — the dataset's canonical Lance shard (``manifest`` s3eoz, else nfs).
    * ``"<dataset>:<enrich-key>"`` — a derived/enriched artifact from the card's ``enrich`` block,
      e.g. ``"ego4d:gpt2_prefix_1p1m"``.

    Each ``manifests`` list entry is resolved independently, so a composite/mixed training set
    (a list of specs + weights) can freely combine base datasets, enrich artifacts, and raw URIs.
    """
    if "://" in spec or "/" in spec or spec.endswith((".lance", ".parquet", ".csv", ".txt", ".json")):
        return spec  # already a path or URI
    if ":" in spec:
        name, key = spec.split(":", 1)
        card = load_card(name, cards_dir=cards_dir)
        if key not in card.enrich:
            msg = f"Dataset '{name}' has no enrich entry '{key}'. Available: {sorted(card.enrich)}"
            raise KeyError(msg)
        return card.enrich[key]
    return load_card(spec, cards_dir=cards_dir).manifest_path


def _find_cards_dir() -> Path:
    """Find the dataset cards directory by walking up from this file."""
    # Walk up from src/gslm2/data/registry.py to repo root
    current = Path(__file__).resolve()
    for parent in current.parents:
        candidate = parent / _DEFAULT_CARDS_DIR
        if candidate.is_dir():
            return candidate
    # Fallback: relative to cwd
    return Path.cwd() / _DEFAULT_CARDS_DIR
